const marker = "# generated by ccroute"

// state records what install changed, so a later install or uninstall can
// take exactly that back out and leave everything else alone.
type state struct {
	Settings      string             `json:"settings"`
	Env           map[string]*string `json:"env"`            // key -> value before ccroute set it (nil: absent)
	Picker        []string           `json:"picker"`         // model IDs of the /model rows ccroute added
	ModelSettings []string           `json:"model_settings"` // model IDs whose autoCompactWindow ccroute set
	Agents        []string           `json:"agents"`         // agent files ccroute wrote
	Service       string             `json:"service,omitempty"`
}

func statePath() string { return filepath.Join(filepath.Dir(defaultConfigPath()), "installed.json") }

func loadState() (*state, error) {
	b, err := os.ReadFile(statePath())
	if errors.Is(err, os.ErrNotExist) {
		return &state{}, nil
	}
	if err != nil {
		return nil, err
	}
	var s state
	if err := json.Unmarshal(b, &s); err != nil {
		return nil, fmt.Errorf("%s: %w", statePath(), err)
	}
	return &s, nil
}

func (s *state) save() error {
	b, _ := json.MarshalIndent(s, "", "  ")
	return writeFile(statePath(), append(b, '\n'), 0o644)
}

func claudeDir() string {
	if d := os.Getenv("CLAUDE_CONFIG_DIR"); d != "" {
		return d
	}
	h, _ := os.UserHomeDir()
	return filepath.Join(h, ".claude")
}

func unitPath() string {
	return filepath.Join(filepath.Dir(filepath.Dir(defaultConfigPath())), "systemd", "user", "ccroute.service")
}

type kv struct{ k, v string }

// clientEnv is the environment Claude Code needs for cfg.
func clientEnv(cfg *Config) []kv {
	env := map[string]string{"ANTHROPIC_BASE_URL": "http://" + dialAddr(cfg.Listen)}
	for _, m := range cfg.Models {
		v, ok := tiers[m.Tier]
		if !ok {
			continue
		}
		env[v] = m.ID
		if strings.HasPrefix(v, "ANTHROPIC_DEFAULT_") && m.Tier != "default" {
			if m.Name != "" {
				env[v+"_NAME"] = m.Name
			}
			if m.Description != "" {
				env[v+"_DESCRIPTION"] = m.Description
			}
		}
	}
	for k, v := range cfg.Env {
		env[k] = v
	}
	out := make([]kv, 0, len(env))
	for k, v := range env {
		out = append(out, kv{k, v})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].k < out[j].k })
	return out
}

// dialAddr turns a listen address into one a client can connect to.
func dialAddr(listen string) string {
	host, port, err := net.SplitHostPort(listen)
	if err != nil {
		return listen
	}
	if host == "" || host == "0.0.0.0" || host == "::" {
		host = "127.0.0.1"
	}
	return net.JoinHostPort(host, port)
}

func printEnv(args []string) error {
	fs := flag.NewFlagSet("env", flag.ExitOnError)
	cfgPath := fs.String("config", defaultConfigPath(), "config file")
	_ = fs.Parse(args)
	cfg, err := loadConfig(*cfgPath)
	if err != nil {
		return err
	}
	for _, e := range clientEnv(cfg) {
		fmt.Printf("export %s='%s'\n", e.k, strings.ReplaceAll(e.v, "'", `'\''`))
	}
	return nil
}

func install(args []string) error {
	fs := flag.NewFlagSet("install", flag.ExitOnError)
	cfgPath := fs.String("config", defaultConfigPath(), "config file")
	settingsPath := fs.String("settings", filepath.Join(claudeDir(), "settings.json"), "Claude Code user settings")
	agentsDir := fs.String("agents", filepath.Join(claudeDir(), "agents"), "Claude Code agents directory")
	noService := fs.Bool("no-service", false, "don't write or restart the systemd user service")
	dry := fs.Bool("dry-run", false, "show what would change, change nothing")
	_ = fs.Parse(args)

	abs, err := filepath.Abs(*cfgPath)
	if err != nil {
		return err
	}
	cfg, err := loadConfig(abs)
	if err != nil {
		return err
	}
	st, err := loadState()
	if err != nil {
		return err
	}
	if st.Settings != "" && st.Settings != *settingsPath {
		return fmt.Errorf("installed into %s before; run ccroute uninstall -settings %s first", st.Settings, st.Settings)
	}
	for _, a := range cfg.Agents {
		if a.Model != "" && cfg.lookup(a.Model) == nil && !strings.HasPrefix(a.Model, "claude") &&
			!map[string]bool{"inherit": true, "haiku": true, "sonnet": true, "opus": true, "fable": true}[a.Model] {
			fmt.Fprintf(os.Stderr, "warning: agent %s uses model %q, which is not in %s\n", a.Name, a.Model, abs)
		}
	}

	settings, err := readSettings(*settingsPath)
	if err != nil {
		return err
	}
	if err := unapply(settings, st); err != nil {
		return err
	}
	next := &state{Settings: *settingsPath, Env: map[string]*string{}}
	if err := apply(settings, cfg, next); err != nil {
		return err
	}
	agents := map[string][]byte{}
	for _, a := range cfg.Agents {
		agents[filepath.Join(*agentsDir, a.Name+".md")] = renderAgent(a, cfg, abs)
	}
	unit := renderUnit(abs, cfg)

	if *dry {
		fmt.Printf("would set in %s:\n", *settingsPath)
		for k, prev := range next.Env {
			v, _ := mustChild(settings, "env").str(k)
			fmt.Printf("  env.%s = %q%s\n", k, v, prevNote(prev))
		}
		for _, id := range next.Picker {
			fmt.Printf("  modelPicker row %s\n", id)
		}
		for _, id := range next.ModelSettings {
			fmt.Printf("  modelSettings.%s.autoCompactWindow\n", id)
		}
		for p, b := range agents {
			fmt.Printf("would write %s:\n%s\n", p, b)
		}
		if !*noService {
			fmt.Printf("would write %s and restart it:\n%s", unitPath(), unit)
		}
		return nil
	}

	// The proxy must answer before Claude Code is pointed at it: with a dead
	// ANTHROPIC_BASE_URL every Claude Code session fails.
	if !*noService {
		if err := installService(unit, cfg); err != nil {
			return err
		}
		next.Service = unitPath()
	} else if st.Service != "" {
		next.Service = st.Service
	}
	if err := waitHealthy(cfg, 2*time.Second); err != nil {
		fmt.Fprintf(os.Stderr, "warning: proxy not answering at %s (%v); Claude Code sessions fail until it runs\n", dialAddr(cfg.Listen), err)
	}

	if err := writeSettings(*settingsPath, settings); err != nil {
		return err
	}
	for _, p := range st.Agents {
		if _, keep := agents[p]; !keep && isGenerated(p) {
			_ = os.Remove(p)
			fmt.Println("removed", p)
		}
	}
	for p, b := range agents {
		if old, err := os.ReadFile(p); err == nil && !bytes.Contains(old, []byte(marker)) {
			if err := os.WriteFile(p+".bak-ccroute", old, 0o644); err != nil {
				return err
			}
			fmt.Printf("%s was not generated by ccroute; saved it as %s.bak-ccroute\n", p, p)
		}
		if err := writeFile(p, b, 0o644); err != nil {
			return err
		}
		next.Agents = append(next.Agents, p)
	}
	sort.Strings(next.Agents)
	if err := next.save(); err != nil {
		return err
	}
	fmt.Printf("installed %d model(s) and %d agent(s) into %s; restart Claude Code sessions to pick up the change\n",
		len(cfg.Models), len(cfg.Agents), *settingsPath)
	return nil
}

func prevNote(prev *string) string {
	if prev == nil {
		return ""
	}
	return fmt.Sprintf(" (was %q)", *prev)
}

func mustChild(o *object, k string) *object {
	c, err := o.child(k)
	if err != nil {
		return newObject()
	}
	return c
}

func uninstall(args []string) error {
	fs := flag.NewFlagSet("uninstall", flag.ExitOnError)
	settingsPath := fs.String("settings", "", "Claude Code user settings (default: where install wrote)")
	noService := fs.Bool("no-service", false, "leave the systemd user service alone")
	_ = fs.Parse(args)
	st, err := loadState()
	if err != nil {
		return err
	}
	if *settingsPath == "" {
		*settingsPath = st.Settings
	}
	if *settingsPath == "" {
		return errors.New("nothing installed")
	}
	settings, err := readSettings(*settingsPath)
	if err != nil {
		return err
	}
	if err := unapply(settings, st); err != nil {
		return err
	}
	// Claude Code first, the proxy second: never leave sessions pointed at a
	// proxy that is gone.
	if err := writeSettings(*settingsPath, settings); err != nil {
		return err
	}
	for _, p := range st.Agents {
		if isGenerated(p) {
			_ = os.Remove(p)
		}
	}
	if !*noService && st.Service != "" {
		_ = exec.Command("systemctl", "--user", "disable", "--now", "ccroute.service").Run()
		_ = os.Remove(st.Service)
		_ = exec.Command("systemctl", "--user", "daemon-reload").Run()
	}
	if err := os.Remove(statePath()); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	fmt.Println("uninstalled; restart Claude Code sessions to pick up the change")
	return nil
}

func readSettings(p string) (*object, error) {
	b, err := os.ReadFile(p)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	o, err := parseObject(b)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", p, err)
	}
	return o, nil
}

func writeSettings(p string, o *object) error {
	if old, err := os.ReadFile(p); err == nil {
		if bytes.Equal(old, o.format()) {
			return nil
		}
		if err := os.WriteFile(p+".bak-ccroute", old, 0o600); err != nil {
			return err
		}
	}
	return writeFile(p, o.format(), 0o644)
}

// unapply removes what st says ccroute put into settings.
func unapply(settings *object, st *state) error {
	env, err := settings.child("env")
	if err != nil {
		return err
	}
	for k, prev := range st.Env {
		if prev == nil {
			env.del(k)
		} else {
			env.set(k, *prev)
		}
	}
	putChild(settings, "env", env)

	if len(st.Picker) > 0 {
		picker, err := settings.child("modelPicker")
		if err != nil {
			return err
		}
		rows, err := pickerRows(picker)
		if err != nil {
			return err
		}
		ours := set(st.Picker)
		kept := []json.RawMessage{}
		for _, r := range rows {
			var row struct {
				Model string `json:"model"`
			}
			if json.Unmarshal(r, &row) != nil || !ours[row.Model] {
				kept = append(kept, r)
			}
		}
		if len(kept) == 0 {
			picker.del("options")
		} else {
			picker.set("options", kept)
		}
		putChild(settings, "modelPicker", picker)
	}

	if len(st.ModelSettings) > 0 {
		ms, err := settings.child("modelSettings")
		if err != nil {
			return err
		}
		for _, id := range st.ModelSettings {
			e, err := ms.child(id)
			if err != nil {
				return err
			}
			e.del("autoCompactWindow")
			putChild(ms, id, e)
		}
		putChild(settings, "modelSettings", ms)
	}
	return nil
}

// apply puts cfg into settings and records each change in st.
func apply(settings *object, cfg *Config, st *state) error {
	env, err := settings.child("env")
	if err != nil {
		return err
	}
	for _, e := range clientEnv(cfg) {
		if old, ok := env.str(e.k); ok && old != e.v {
			st.Env[e.k] = &old
		} else {
			st.Env[e.k] = nil
		}
		env.set(e.k, e.v)
	}
	putChild(settings, "env", env)

	var rows []json.RawMessage
	for _, m := range cfg.Models {
		// A haiku/sonnet/opus/fable tier already shows as that family's row.
		if m.Hidden || (m.Tier != "" && m.Tier != "subagent" && m.Tier != "default") {
			continue
		}
		r := map[string]any{"model": m.ID, "label": firstNonEmpty(m.Name, m.ID)}
		if m.Description != "" {
			r["description"] = m.Description
		}
		if m.BehavesAs != "" {
			r["behavesAs"] = m.BehavesAs
		}
		rows = append(rows, raw(r))
		st.Picker = append(st.Picker, m.ID)
	}
	if len(rows) > 0 {
		picker, err := settings.child("modelPicker")
		if err != nil {
			return err
		}
		existing, err := pickerRows(picker)
		if err != nil {
			return err
		}
		picker.set("options", append(existing, rows...))
		putChild(settings, "modelPicker", picker)
	}

	ms, err := settings.child("modelSettings")
	if err != nil {
		return err
	}
	for _, m := range cfg.Models {
		if m.Context == 0 {
			continue
		}
		e, err := ms.child(m.ID)
		if err != nil {
			return err
		}
		e.set("autoCompactWindow", m.Context)
		putChild(ms, m.ID, e)
		st.ModelSettings = append(st.ModelSettings, m.ID)
	}
	putChild(settings, "modelSettings", ms)
	return nil
}

// pickerRows returns modelPicker.options with each row's bytes as written.
func pickerRows(picker *object) ([]json.RawMessage, error) {
	var rows []json.RawMessage
	if r, ok := picker.vals["options"]; ok {
		if err := json.Unmarshal(r, &rows); err != nil {
			return nil, fmt.Errorf("modelPicker.options: %w", err)
		}
	}
	return rows, nil
}

// putChild stores c under k, or removes k when c is empty.
func putChild(o *object, k string, c *object) {
	if c.len() == 0 {
		o.del(k)
		return
	}
	o.set(k, c)
}

func set(ss []string) map[string]bool {
	m := map[string]bool{}
	for _, s := range ss {
		m[s] = true
	}
	return m
}

func firstNonEmpty(ss ...string) string {
	for _, s := range ss {
		if s != "" {
			return s
		}
	}
	return ""
}

func isGenerated(p string) bool {
	b, err := os.ReadFile(p)
	return err == nil && bytes.Contains(b, []byte(marker))
}

func renderAgent(a *Agent, cfg *Config, cfgPath string) []byte {
	var b strings.Builder
	q := func(s string) string { return string(raw(s)) } // a JSON string is a YAML double-quoted scalar
	fmt.Fprintf(&b, "---\nname: %s\ndescription: %s\n", a.Name, q(a.Description))
	if a.Model != "" {
		fmt.Fprintf(&b, "model: %s\n", q(a.Model))
	}
	if len(a.Tools) > 0 {
		fmt.Fprintf(&b, "tools: %s\n", strings.Join(a.Tools, ", "))
	}
	if len(a.DisallowedTools) > 0 {
		fmt.Fprintf(&b, "disallowedTools: %s\n", strings.Join(a.DisallowedTools, ", "))
	}
	_, hasWindow := a.Extra["autoCompactWindow"]
	if m := cfg.lookup(a.Model); m != nil && m.Context > 0 && !hasWindow {
		fmt.Fprintf(&b, "autoCompactWindow: %d\n", m.Context)
	}
	keys := make([]string, 0, len(a.Extra))
	for k := range a.Extra {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(&b, "%s: %s\n", k, q(a.Extra[k]))
	}
	fmt.Fprintf(&b, "%s from %s: edit it there and run `ccroute install`\n---\n\n", marker, cfgPath)
	b.WriteString(strings.TrimSpace(a.Prompt))
	b.WriteString("\n")
	return []byte(b.String())
}

func renderUnit(cfgPath string, cfg *Config) string {
	exe, err := os.Executable()
	if err == nil {
		exe, _ = filepath.EvalSymlinks(exe)
	}
	var b strings.Builder
	b.WriteString("# " + marker[2:] + " install\n[Unit]\nDescription=ccroute: foreign models for Claude Code\n")
	b.WriteString("After=network-online.target\nWants=network-online.target\n\n[Service]\nType=simple\n")
	fmt.Fprintf(&b, "ExecStart=%s serve -config %s\n", unitQuote(exe), unitQuote(cfgPath))
	home, _ := os.UserHomeDir()
	for _, f := range cfg.EnvFiles {
		if strings.HasPrefix(f, "~/") {
			f = filepath.Join(home, f[2:])
		}
		fmt.Fprintf(&b, "EnvironmentFile=-%s\n", strings.ReplaceAll(f, "%", "%%"))
	}
	b.WriteString("Restart=on-failure\nRestartSec=3\nNoNewPrivileges=true\nPrivateTmp=true\n\n[Install]\nWantedBy=default.target\n")
	return b.String()
}

func unitQuote(s string) string {
	s = strings.ReplaceAll(s, "%", "%%")
	if !strings.ContainsAny(s, " \t\"\\'") {
		return s
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// installService writes the unit and restarts it; if the new proxy does not
// come up healthy, the previous unit is put back and restarted.
func installService(unit string, cfg *Config) error {
	if exe, _ := os.Executable(); strings.HasPrefix(exe, os.TempDir()) {
		return fmt.Errorf("running from %s (go run?): install the binary first (go install .)", exe)
	}
	p := unitPath()
	old, oldErr := os.ReadFile(p)
	if err := writeFile(p, []byte(unit), 0o644); err != nil {
		return err
	}
	systemctl := func(a ...string) error {
		out, err := exec.Command("systemctl", append([]string{"--user"}, a...)...).CombinedOutput()
		if err != nil {
			return fmt.Errorf("systemctl %s: %v: %s", strings.Join(a, " "), err, bytes.TrimSpace(out))
		}
		return nil
	}
	err := systemctl("daemon-reload")
	if err == nil {
		err = systemctl("enable", "ccroute.service")
	}
	if err == nil {
		err = systemctl("restart", "ccroute.service")
	}
	if err == nil {
		err = waitHealthy(cfg, 5*time.Second)
	}
	if err == nil {
		return nil
	}
	if oldErr == nil {
		_ = os.WriteFile(p, old, 0o644)
		_ = systemctl("daemon-reload")
		_ = systemctl("restart", "ccroute.service")
		return fmt.Errorf("new proxy did not start (%w); restored the previous unit. See journalctl --user -u ccroute", err)
	}
	return fmt.Errorf("proxy did not start: %w. See journalctl --user -u ccroute", err)
}

func waitHealthy(cfg *Config, d time.Duration) error {
	c := &http.Client{Timeout: time.Second}
	u := "http://" + dialAddr(cfg.Listen) + "/ccroute/health"
	deadline := time.Now().Add(d)
	for {
		resp, err := c.Get(u)
		if err == nil {
			resp.Body.Close()
			if resp.StatusCode == http.StatusOK {
				return nil
			}
			err = fmt.Errorf("%s: %s", u, resp.Status)
		}
		if time.Now().After(deadline) {
			return err
		}
		time.Sleep(200 * time.Millisecond)
	}
}

func writeFile(p string, b []byte, mode os.FileMode) error {
	if t, err := filepath.EvalSymlinks(p); err == nil {
		p = t // keep a symlinked settings file (dotfiles) a symlink
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), "."+filepath.Base(p)+".*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(b); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(mode); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), p)
}

// check sends a short prompt to each model through the same code path Claude
// Code's requests take, once plain and once streaming.
func check(args []string) error {
	fs := flag.NewFlagSet("check", flag.ExitOnError)
	cfgPath := fs.String("config", defaultConfigPath(), "config file")
	_ = fs.Parse(args)
	cfg, err := loadConfig(*cfgPath)
	if err != nil {
		return err
	}
	px, err := newProxy(cfg)
	if err != nil {
		return err
	}
	want := set(fs.Args())
	failed := 0
	for _, m := range cfg.Models {
		if len(want) > 0 && !want[m.ID] {
			continue
		}
		for _, stream := range []bool{false, true} {
			body, _ := json.Marshal(map[string]any{
				"model": m.ID, "max_tokens": 256, "stream": stream,
				"messages": []map[string]any{{"role": "user", "content": "Reply with the single word OK."}},
			})
			req := httptest.NewRequest(http.MethodPost, "/v1/messages", bytes.NewReader(body))
			req.Header.Set("Content-Type", "application/json")
			req.Header.Set("Anthropic-Version", "2023-06-01")
			w := httptest.NewRecorder()
			start := time.Now()
			px.ServeHTTP(w, req)
			res := w.Result()
			out, _ := io.ReadAll(res.Body)
			text, model := summarize(out, stream)
			status := "ok"
			if res.StatusCode != http.StatusOK || text == "" {
				status = "FAIL"
				failed++
			}
			kind := "plain"
			if stream {
				kind = "stream"
			}
			fmt.Printf("%-4s %s (%s, %s) %d in %s: model %q, reply %q\n", status, m.ID, m.API, kind, res.StatusCode,
				time.Since(start).Round(time.Millisecond), model, truncate(text, 80))
			if status == "FAIL" && text == "" {
				fmt.Printf("     %s\n", truncate(string(out), 300))
			}
		}
	}
	if failed > 0 {
		return fmt.Errorf("%d check(s) failed", failed)
	}
	return nil
}

// summarize returns the reply text and the model a response reports.
func summarize(b []byte, stream bool) (text, model string) {
	if !stream {
		var r struct {
			Model   string `json:"model"`
			Content []struct {
				Type, Text string
			} `json:"content"`
		}
		_ = json.Unmarshal(b, &r)
		for _, c := range r.Content {
			text += c.Text
		}
		return text, r.Model
	}
	for _, line := range strings.Split(string(b), "\n") {
		d, ok := strings.CutPrefix(line, "data: ")
		if !ok {
			continue
		}
		var ev struct {
			Type    string `json:"type"`
			Message struct {
				Model string `json:"model"`
			} `json:"message"`
			Delta struct {
				Text string `json:"text"`
			} `json:"delta"`
		}
		if json.Unmarshal([]byte(d), &ev) != nil {
			continue
		}
		switch ev.Type {
		case "message_start":
			model = ev.Message.Model
		case "content_block_delta":
			text += ev.Delta.Text
		}
	}
	return text, model
}

func truncate(s string, n int) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > n {
		return s[:n] + "…"
	}
	return s
}

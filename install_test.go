package main

import (
	"strings"
	"testing"
)

const userSettings = `{
  "permissions": {
    "allow": [
      "Bash(echo <x> && y)"
    ]
  },
  "model": "opus",
  "note": "dash — kept",
  "env": {
    "FOO": "bar",
    "ANTHROPIC_BASE_URL": "http://127.0.0.1:8098"
  },
  "modelPicker": {
    "options": [
      {
        "model": "claude-opus-5-5",
        "label": "Mine"
      }
    ]
  },
  "modelSettings": {
    "local-a": {
      "effortLevel": "low"
    }
  }
}
`

func TestSettingsRoundTripIsByteStable(t *testing.T) {
	o, err := parseObject([]byte(userSettings))
	if err != nil {
		t.Fatal(err)
	}
	if got := string(o.format()); got != userSettings {
		t.Errorf("round trip changed the file:\n%s", got)
	}
}

func testConfig(t *testing.T) *Config {
	t.Helper()
	cfg := &Config{
		Models: []*Model{
			{ID: "local-a", Upstream: "http://127.0.0.1:8003", Name: "Local A", Description: "fast", BehavesAs: "claude-haiku-5-5", Context: 128000},
			{ID: "remote-b", Upstream: "https://example.com/v1", API: "openai", KeyEnv: "B_KEY", Tier: "haiku", Name: "B"},
			{ID: "hidden-c", Upstream: "http://127.0.0.1:9000", Hidden: true},
		},
		Agents: []*Agent{{Name: "worker", Description: `Does "things": fast`, Model: "local-a", Prompt: "  Do it.\n",
			DisallowedTools: []string{"Agent", "SendMessage"}, Extra: map[string]string{"color": "cyan"}}},
		Env: map[string]string{"CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS": "1"},
	}
	if err := cfg.validate(); err != nil {
		t.Fatal(err)
	}
	return cfg
}

func TestApplyThenUnapplyRestores(t *testing.T) {
	cfg := testConfig(t)
	o, _ := parseObject([]byte(userSettings))
	st := &state{Env: map[string]*string{}}
	if err := apply(o, cfg, st); err != nil {
		t.Fatal(err)
	}
	got := string(o.format())
	for _, want := range []string{
		`"ANTHROPIC_DEFAULT_HAIKU_MODEL": "remote-b"`,
		`"ANTHROPIC_DEFAULT_HAIKU_MODEL_NAME": "B"`,
		`"CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS": "1"`,
		`"FOO": "bar"`,
		`"label": "Mine"`,
		`"behavesAs": "claude-haiku-5-5"`,
		`"label": "Local A"`,
		`"effortLevel": "low"`,
		`"autoCompactWindow": 128000`,
		`Bash(echo <x> && y)`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %s in\n%s", want, got)
		}
	}
	if strings.Contains(got, "hidden-c") || strings.Contains(got, `"model": "remote-b"`) {
		t.Errorf("hidden or tier model got a picker row:\n%s", got)
	}
	// ANTHROPIC_BASE_URL already had our value: uninstall removes it.
	if st.Env["ANTHROPIC_BASE_URL"] != nil {
		t.Errorf("prev base URL recorded as %q", *st.Env["ANTHROPIC_BASE_URL"])
	}

	// A second install with the same config changes nothing.
	again, _ := parseObject(o.format())
	if err := unapply(again, st); err != nil {
		t.Fatal(err)
	}
	st2 := &state{Env: map[string]*string{}}
	if err := apply(again, cfg, st2); err != nil {
		t.Fatal(err)
	}
	if string(again.format()) != got {
		t.Errorf("reinstall changed settings:\n%s", again.format())
	}

	if err := unapply(o, st); err != nil {
		t.Fatal(err)
	}
	want := strings.Replace(userSettings, `,
    "ANTHROPIC_BASE_URL": "http://127.0.0.1:8098"`, "", 1)
	if got := string(o.format()); got != want {
		t.Errorf("unapply did not restore:\n%s", got)
	}
}

func TestUnapplyRestoresPreviousValue(t *testing.T) {
	cfg := testConfig(t)
	o, _ := parseObject([]byte(`{"env":{"ANTHROPIC_DEFAULT_HAIKU_MODEL":"claude-haiku-4-5"}}`))
	st := &state{Env: map[string]*string{}}
	if err := apply(o, cfg, st); err != nil {
		t.Fatal(err)
	}
	if err := unapply(o, st); err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(strings.Fields(string(o.format())), ""); got != `{"env":{"ANTHROPIC_DEFAULT_HAIKU_MODEL":"claude-haiku-4-5"}}` {
		t.Errorf("got %s", got)
	}
}


func TestValidate(t *testing.T) {
	for _, tc := range []struct {
		m    Model
		want string
	}{
		{Model{Upstream: "http://x"}, "id is required"},
		{Model{ID: "a", Upstream: "x"}, "scheme"},
		{Model{ID: "a", Upstream: "http://x", API: "grpc"}, "api"},
		{Model{ID: "a", Upstream: "http://x", Auth: "bearer"}, "key_env"},
		{Model{ID: "a", Upstream: "http://x", Tier: "mini"}, "tier"},
		{Model{ID: "a", Upstream: "http://x", Context: 32000}, "100000"},
	} {
		if err := tc.m.validate(); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%+v: %v, want %q", tc.m, err, tc.want)
		}
	}
	m := Model{ID: "a", Upstream: "https://x/v1", API: "openai", KeyEnv: "K"}
	if err := m.validate(); err != nil || m.Auth != "bearer" || m.UpstreamModel != "a" {
		t.Errorf("defaults: %v %+v", err, m)
	}
}
